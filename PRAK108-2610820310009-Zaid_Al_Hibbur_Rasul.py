putaran = 5
jarak_total = 14
pi = 3.14

keliling_taman = jarak_total / putaran
luas_taman = keliling_taman / (2 * pi)

print(f"Diketahui :\n")
print(f"Pak Dengklek mengelilingi taman = {putaran} putaran\n")
print(f"Jarak tempuh Pak Dengklek = {jarak_total} Kilometer\n\n")
print(f"Jawaban :\n")
print(f"Jari-jari taman yang dikelilingi Pak Dengklek adalah {luas_taman:.2f} Kilometer")